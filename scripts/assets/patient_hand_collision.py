"""Exact triangle crossing checks for patient hand/hand and hand/shirt pairs.
Input: collision exports generated by patient_rest_hands.mjs.
Checks original world-space breathing fill 0, 0.5, 1. No installed project deps.
Uses the existing asset Python numpy environment; no triangle acceleration package.
"""
import json,numpy as np
from pathlib import Path
import sys
P=Path(sys.argv[1])
def intersect(a,b):
 amin=a.min(1);amax=a.max(1);bmin=b.min(1);bmax=b.max(1);hits=[]
 def segments(o,d,t):
  e1=t[:,1]-t[:,0];e2=t[:,2]-t[:,0];h=np.cross(d,e2);det=np.einsum('ij,ij->i',e1,h);good=np.abs(det)>1e-12;inv=1/np.where(good,det,1);s=o-t[:,0];u=inv*np.einsum('ij,ij->i',s,h);q=np.cross(s,e1);v=inv*np.einsum('ij,ij->i',d,q);dist=inv*np.einsum('ij,ij->i',e2,q);return good&(u>=-1e-7)&(v>=-1e-7)&(u+v<=1+1e-7)&(dist>1e-7)&(dist<1-1e-7)
 for i,t in enumerate(a):
  ids=np.flatnonzero(np.all(bmax>=amin[i]-1e-8,axis=1)&np.all(bmin<=amax[i]+1e-8,axis=1))
  if not len(ids):continue
  bt=b[ids];h=np.zeros(len(ids),bool)
  for k in range(3):h|=segments(np.broadcast_to(t[k],(len(ids),3)),np.broadcast_to(t[(k+1)%3]-t[k],(len(ids),3)),bt);h|=segments(bt[:,k],bt[:,(k+1)%3]-bt[:,k],np.broadcast_to(t,(len(ids),3,3)))
  hits.extend((i,int(j)) for j in ids[h])
 return hits
def vertical_gap(points,triangles):
 lo=points[:,:2].min(0);hi=points[:,:2].max(0);keep=np.all(triangles[:,:,:2].max(1)>=lo,axis=1)&np.all(triangles[:,:,:2].min(1)<=hi,axis=1);t=triangles[keep]
 if not len(t):return None
 a,b,c=t[:,0],t[:,1],t[:,2];den=(b[:,1]-c[:,1])*(a[:,0]-c[:,0])+(c[:,0]-b[:,0])*(a[:,1]-c[:,1]);valid=np.abs(den)>1e-12;den=np.where(valid,den,1);best=float('inf')
 for offset in range(0,len(points),128):
  v=points[offset:offset+128];x=v[:,None,0];y=v[:,None,1];u=((b[:,1]-c[:,1])*(x-c[:,0])+(c[:,0]-b[:,0])*(y-c[:,1]))/den;w=((c[:,1]-a[:,1])*(x-c[:,0])+(a[:,0]-c[:,0])*(y-c[:,1]))/den;r=1-u-w;inside=(u>=-1e-7)&(w>=-1e-7)&(r>=-1e-7)&valid;z=u*a[:,2]+w*b[:,2]+r*c[:,2];z=np.where(inside,z,-np.inf).max(1);gap=v[:,2]-z;best=min(best,float(gap.min()))
 return round(best*1000,4) if np.isfinite(best) else None

def run_patient(f):
 d=json.load(open(f));entry={'patient':f.name[:9],'breathing':[]}
 for fill in [0,.5,1]:
  m={x['name']:(np.array(x['positions'])+fill*np.array(x.get('breathDeltas',np.zeros_like(x['positions']))),np.array(x['triangles'])) for x in d};out={'fill':fill}
  for a,b in [('hand0','hand1'),('hand0','shirt'),('hand1','shirt')]:
   av,ai=m[a];bv,bi=m[b];at=av[ai];bt=bv[bi];hits=intersect(at,bt);va=av[np.unique(ai)];vb=bv[np.unique(bi)];gap=min(np.linalg.norm(va[i:i+128,None]-vb[None],axis=2).min() for i in range(0,len(va),128));out[a+'/'+b]={'triangleIntersections':len(hits),'closestSampledVertexGapMM':round(float(gap)*1000,3)}
   # hand0 is the lower/right resting hand; hand1 rests above it.
   if a=='hand0' and b=='hand1':out[a+'/'+b]['verticalSurfaceClearanceMM']=vertical_gap(vb,at)
   elif b=='shirt':out[a+'/'+b]['verticalSurfaceClearanceMM']=vertical_gap(va,bt)
  entry['breathing'].append(out)
 return entry

if __name__=='__main__':
 from concurrent.futures import ProcessPoolExecutor,as_completed
 files=sorted(P.glob('patient0*-collision.json'))
 if len(sys.argv)>2:files=[f for f in files if f.name.startswith(sys.argv[2])]
 if not files:raise SystemExit('No collision exports found; run patient_rest_hands.mjs first.')
 report=[]
 with ProcessPoolExecutor(max_workers=min(3,len(files))) as pool:
  futures=[pool.submit(run_patient,f) for f in files]
  for f in as_completed(futures):
   item=f.result();report.append(item);print(json.dumps(item),flush=True)
 report.sort(key=lambda i:i['patient']);(P/'patient-collision-report.json').write_text(json.dumps(report,indent=2))
 if any(v['triangleIntersections'] for e in report for b in e['breathing'] for k,v in b.items() if k!='fill'):sys.exit(1)
