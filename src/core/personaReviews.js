/* 별 후기 후보. 이름을 아는 환자는 자기 후기만, 모르면 일반 후기. */
export function starPool(name, stars, generic = []){
  const own = PERSONA_REVIEWS[name];
  const kind = stars >= 2 ? "good" : "rough";
  return own ? own[kind] : generic;
}

/* used: 이번 결과 카드에서 이미 쓴 후기 집합. 쓴 건 빼고 고르고, 다 썼으면 그 풀에서 그대로 고른다. */
export function chooseReview(pool, used, rand = Math.random){
  const fresh = used ? pool.filter(l => !used.has(l)) : pool;
  const from = fresh.length ? fresh : pool;
  const line = from[Math.min(from.length - 1, Math.floor(rand()*from.length))];
  if(used) used.add(line);
  return line;
}
