/* 의뢰별 후일담 줄. 도감 카드는 환자의 의뢰(들)를 편 순서대로 보여 준다. */
export const talesOf = name => QUESTS.filter(q => q.who === name).map(q => ({ ep: q.ep, title: q.title, id: q.id, line: TALES[q.id] }));

/* 지금 읽을 수 있는 후일담: 의뢰를 깬(별 1개 이상) 줄만 line이 있고, 나머지는 null(잠김) */
export function readableTales(prog, name){
  return talesOf(name).map(t => ({ ...t, line: questStars(prog, QUESTS.find(q => q.id === t.id)) > 0 ? t.line : null }));
}
export const taleCounts = prog => ({
  read: QUESTS.filter(q => questStars(prog, q) > 0).length, total: QUESTS.length,
  done: [...new Set(QUESTS.map(q => q.who))].filter(w => QUESTS.filter(q => q.who === w).every(q => questStars(prog, q) > 0)).length,
  regulars: new Set(QUESTS.map(q => q.who)).size
});
/* 후일담 칭호: 반 이상은 수집가, 전부는 박사. 없으면 "" */
export function taleTitle(prog){
  const c = taleCounts(prog);
  if(c.read === c.total) return "뒷이야기 박사";
  if(c.read >= c.total / 2) return "뒷이야기 수집가";
  if(c.read >= 6) return "귀 밝은 단골";
  return "";
}
