/* the day (index) a regular first shows up in the 영업 일지 */
const firstDayOf = name => DAYS.findIndex(d => d.patients.includes(name));
/* a quest opens once every patient in it has appeared in a cleared day */
export const questUnlockDay = q => Math.max(...q.patients.map(firstDayOf));
const byId = id => QUESTS.find(q => q.id === id);
export const questStars = (prog, q) => Math.max(0, Math.min(3, (prog.quests && prog.quests[q.id]) | 0));
export function questOpen(prog, q){
  if(prog.cleared <= questUnlockDay(q)) return false;
  return q.ep === 1 || questStars(prog, byId(`${q.who}${q.ep - 1}`)) > 0;
}
export const questClears = (q, complete, avg) => dayClears(-1, complete, avg, q);
export const questStarsOf = (q, avg) => dayStars(avg, q);
/* a cleared quest keeps its best stars; a miss changes nothing */
export function afterQuest(prog, q, cleared, stars){
  if(!cleared) return prog;
  const quests = {...(prog.quests || {})};
  quests[q.id] = Math.max(quests[q.id] | 0, stars);
  return {...prog, quests};
}
/* the quest's patients from the roster, in order, with the quest's start line */
export function questRoster(i, roster){
  const q = QUESTS[i];
  return q.patients.map(name => {
    const p = roster.find(r => r.name === name);
    if(!p) throw new Error("no patient " + name);
    const start = q.lines && q.lines[name];
    return start ? {...p, lines: {...p.lines, start}} : p;
  });
}
/* board order: by when the quest opens, then episode */
export const questOrder = () => QUESTS.map((q, i) => i).sort((a, b) => questUnlockDay(QUESTS[a]) - questUnlockDay(QUESTS[b]) || QUESTS[a].ep - QUESTS[b].ep || a - b);
