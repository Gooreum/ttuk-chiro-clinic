function build(who, ep, title, game, patients, rule, intro, outro, line){
  const q = {
    id: `${who}${ep}`, who, ep, title, game, patients, rule, zone: 0, intro, outro, lines: {[who]: line},
    painMax: rule === "pain1" ? 1 : rule === "pain2" ? 2 : 3
  };
  if(rule === "tight") q.mods = {tight: true};
  if(rule === "noisy") q.mods = {noisy: true};
  if(rule === "beat") q.beat = Math.round(STAR_CUTS.three + cutShift(q) - QUEST_GAP);
  return q;
}
